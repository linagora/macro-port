<#
.SYNOPSIS
  Builds binary Excel fixtures (.xlsm, .xlsb, .xls) for Macro-Port from the text corpus, using Excel itself.

.DESCRIPTION
  Run once on a Windows workstation with Microsoft Excel installed (not in CI).
  Prerequisite: in Excel, File > Options > Trust Center > Trust Center Settings > Macro Settings,
  tick "Trust access to the VBA project object model". Untick it again when done.

  For each corpus sample (.bas, .cls) the script creates a workbook, injects the code, and saves it
  in three formats. It never runs any macro: workbooks are created with macros disabled
  (AutomationSecurity = msoAutomationSecurityForceDisable) and only the VBA editor object model is used.

  Also produces:
    - an encrypted workbook (file-open password) -> expected status "encrypted";
    - a workbook with an Excel 4.0 macro sheet containing only =RETURN() -> expected xlm.present = true.
  Password-protected VBA projects cannot be created through COM: protect 3 of the generated .xlsm files
  manually (VBA editor > Tools > VBAProject Properties > Protection) and list them in fixtures.yaml.

  .frm samples are skipped: their .frx companion files are not in the corpus.

  Antivirus: the family 14 samples are benign but deliberately look suspicious (Auto_Open + Shell, obfuscated
  WScript.Shell, download pattern). Microsoft Defender is likely to quarantine the generated files. Use a dedicated
  output folder excluded from real-time scanning, with the approval of your security officer, and keep the
  fixtures out of shared drives.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\Build-Fixtures.ps1 -CorpusRoot ..\..\corpus -OutDir ..\..\corpus\fixtures\generated
#>
param(
  [Parameter(Mandatory = $true)] [string] $CorpusRoot,
  [Parameter(Mandatory = $true)] [string] $OutDir
)

$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSVersion.Major -ne 5) { throw "Run with Windows PowerShell 5.1 (powershell.exe), not PowerShell 7: COM and ANSI encoding behave differently." }
$ansiCodePage = (Get-Culture).TextInfo.ANSICodePage
$ansi = [System.Text.Encoding]::GetEncoding($ansiCodePage)
$CorpusRoot = (Resolve-Path $CorpusRoot).Path
New-Item -ItemType Directory -Force -Path $OutDir | Out-Null
$OutDir = (Resolve-Path $OutDir).Path

# Excel file formats
$formats = @(
  @{ Ext = 'xlsm'; Code = 52 },
  @{ Ext = 'xlsb'; Code = 50 },
  @{ Ext = 'xls';  Code = 56 }
)
# VBA component types
$vbext_ct_StdModule = 1
$vbext_ct_ClassModule = 2

function Remove-CorpusHeader([string] $text) {
  # Drop the corpus header block (SPEC section 5): lines "' Source:|Author:|License:|Retrieved:|Family:|Synthetic:"
  # at the top, followed by one line consisting of a single "'". Everything else is kept verbatim.
  $lines = $text -split "`r?`n"
  $i = 0
  while ($i -lt $lines.Count -and $lines[$i] -match "^' (Source|Author|License|Retrieved|Family|Synthetic):") { $i++ }
  if ($i -gt 0 -and $i -lt $lines.Count -and $lines[$i] -eq "'") { $i++ }
  return ($lines[$i..($lines.Count - 1)] -join "`r`n")
}

function Get-CodeBody([string] $text) {
  # Remove the export headers (VERSION, BEGIN..END, Attribute lines) that AddFromString does not accept.
  $out = New-Object System.Collections.Generic.List[string]
  $inBegin = $false
  foreach ($l in ($text -split "`r?`n")) {
    if ($l -match '^VERSION\s') { continue }
    if ($l -match '^BEGIN\s*$') { $inBegin = $true; continue }
    if ($inBegin) { if ($l -match '^END\s*$') { $inBegin = $false }; continue }
    if ($l -match '^Attribute\s+') { continue }   # module-level and procedure-level attributes
    $out.Add($l)
  }
  return ($out -join "`r`n")
}

function Test-DocumentModule([string] $body) {
  return ($body -match '(?im)^\s*Private\s+Sub\s+(Workbook|Worksheet)_\w+')
}

$excel = New-Object -ComObject Excel.Application
$excel.Visible = $false
$excel.DisplayAlerts = $false
$excel.EnableEvents = $false
$excel.AutomationSecurity = 3   # msoAutomationSecurityForceDisable: never run macros

$manifest = New-Object System.Collections.Generic.List[string]
$manifest.Add('# Generated by Build-Fixtures.ps1. Expected content of each binary fixture (ACCEPTANCE A1).')
$manifest.Add("generated: $(Get-Date -Format s)")
$manifest.Add("excel_version: '$($excel.Version)'")
$manifest.Add('fixtures:')

try {
  $samples = Get-ChildItem -Path (Join-Path $CorpusRoot 'families') -Recurse -Include *.bas, *.cls
  foreach ($s in $samples) {
    $raw = Get-Content -Raw -Encoding UTF8 -Path $s.FullName
    $clean = Remove-CorpusHeader $raw
    $code = Get-CodeBody $clean
    $id = $s.BaseName.Substring(0, 5)
    $isDoc = ($s.Extension -eq '.cls') -and (Test-DocumentModule $code)

    foreach ($f in $formats) {
      $wb = $excel.Workbooks.Add()
      try {
        $proj = $wb.VBProject
        if ($isDoc) {
          # Document module: replace the content of ThisWorkbook or of the first sheet module.
          $target = $proj.VBComponents.Item($wb.CodeName)
          if ($code -match '(?im)^\s*Private\s+Sub\s+Worksheet_') {
            $target = $proj.VBComponents | Where-Object { $_.Type -eq 100 -and $_.Name -ne $wb.CodeName } | Select-Object -First 1
          }
          $cm = $target.CodeModule
          if ($cm.CountOfLines -gt 0) { $cm.DeleteLines(1, $cm.CountOfLines) }
          $cm.AddFromString($code)
          $modName = $target.Name; $modType = 'document'
        } else {
          # Standard or class module: VBComponents.Import keeps Attribute lines semantics (AddFromString does not).
          $tmpName = ('M_' + ($id -replace '-', '_'))
          $body = $clean -replace '(?m)^Attribute VB_Name = ".*"\r?$', ''
          if ($s.Extension -eq '.cls' -and $body -notmatch '(?m)^VERSION 1\.0 CLASS') {
            $body = "VERSION 1.0 CLASS`r`nBEGIN`r`n  MultiUse = -1  'True`r`nEND`r`n" + $body
          }
          if ($s.Extension -eq '.cls') {
            $body = ([regex]'(?m)^END\r?$').Replace($body, "END`r`nAttribute VB_Name = `"$tmpName`"", 1)
          } else {
            $body = "Attribute VB_Name = `"$tmpName`"`r`n" + $body
          }
          $tmp = Join-Path $env:TEMP ("{0}{1}" -f $tmpName, $s.Extension)
          [System.IO.File]::WriteAllText($tmp, $body, $ansi)
          $comp = $proj.VBComponents.Import($tmp)
          Remove-Item $tmp
          $modName = $comp.Name; $modType = if ($comp.Type -eq 1) { 'standard' } else { 'class' }
        }
        $out = Join-Path $OutDir ("{0}.{1}" -f $s.BaseName, $f.Ext)
        $wb.SaveAs($out, $f.Code)
        # Reference source as Excel stores it (the VBA editor normalises identifier casing and drops some characters
        # outside the system code page): A1 compares extraction against this export, not against the corpus text.
        $refExt = if ($modType -eq 'standard') { 'bas' } else { 'cls' }
        $ref = Join-Path $OutDir ("{0}.{1}.expected.{2}" -f $s.BaseName, $f.Ext, $refExt)
        $proj.VBComponents.Item($modName).Export($ref)
        $manifest.Add("  - file: generated/$($s.BaseName).$($f.Ext)")
        $manifest.Add("    source: families/$($s.Directory.Name)/$($s.Name)")
        $manifest.Add("    code_page: $ansiCodePage")
        $manifest.Add("    modules:")
        foreach ($c in $proj.VBComponents) {
          $t = switch ($c.Type) { 1 { 'standard' } 2 { 'class' } 3 { 'form' } 100 { 'document' } default { 'other' } }
          if ($c.Name -eq $modName) {
            $manifest.Add("      - { name: $($c.Name), type: $t, expected_source: generated/$(Split-Path $ref -Leaf) }")
          } else {
            $manifest.Add("      - { name: $($c.Name), type: $t }")
          }
        }
      } catch {
        Write-Warning "Skipped $($s.Name) as $($f.Ext): $($_.Exception.Message)"
      } finally {
        $wb.Close($false)
      }
    }
  }

  # Encrypted workbook (file-open password). Expected status: encrypted.
  $wb = $excel.Workbooks.Add()
  $c = $wb.VBProject.VBComponents.Add($vbext_ct_StdModule)
  $c.CodeModule.AddFromString("Sub Hello()`r`n    Debug.Print ""encrypted fixture""`r`nEnd Sub")
  $wb.SaveAs((Join-Path $OutDir 'enc-01-open-password.xlsm'), 52, 'macro-port-test')
  $wb.Close($false)
  $manifest.Add('  - file: generated/enc-01-open-password.xlsm')
  $manifest.Add('    expected_status: encrypted')

  # Encrypted .xls (FILEPASS): only the Workbook stream is encrypted, VBA must still be extracted.
  $wb = $excel.Workbooks.Add()
  $c = $wb.VBProject.VBComponents.Add($vbext_ct_StdModule)
  $c.CodeModule.AddFromString("Sub Hello()`r`n    Debug.Print ""encrypted xls fixture""`r`nEnd Sub")
  $encName = $c.Name
  $wb.SaveAs((Join-Path $OutDir 'enc-02-open-password.xls'), 56, 'macro-port-test')
  $wb.Close($false)
  $manifest.Add('  - file: generated/enc-02-open-password.xls')
  $manifest.Add('    expected_status: ok')
  $manifest.Add('    expected_workbook_encrypted: true')
  $manifest.Add("    expected_module: $encName")

  # Excel 4.0 macro sheet with a single inert formula. Expected: xlm.present = true, macro_sheets = 1.
  foreach ($f in @(@{ Ext = 'xlsm'; Code = 52 }, @{ Ext = 'xls'; Code = 56 })) {
    $wb = $excel.Workbooks.Add()
    $ms = $wb.Excel4MacroSheets.Add()
    $ms.Range('A1').Formula = '=RETURN()'
    $wb.SaveAs((Join-Path $OutDir ("xlm-01-macrosheet.{0}" -f $f.Ext)), $f.Code)
    $wb.Close($false)
    $manifest.Add("  - file: generated/xlm-01-macrosheet.$($f.Ext)")
    $manifest.Add('    expected_xlm: { present: true, macro_sheets: 1 }')
  }

  # Workbook without macros, saved as .xlsm. Expected status: no_macros.
  $wb = $excel.Workbooks.Add()
  $wb.SaveAs((Join-Path $OutDir 'none-01-no-macros.xlsm'), 52)
  $wb.Close($false)
  $manifest.Add('  - file: generated/none-01-no-macros.xlsm')
  $manifest.Add('    expected_status: no_macros')
}
finally {
  $excel.Quit()
  [System.Runtime.InteropServices.Marshal]::ReleaseComObject($excel) | Out-Null
}

$manifestPath = Join-Path (Split-Path $OutDir -Parent) 'fixtures.yaml'
$manifest | Set-Content -Encoding UTF8 -Path $manifestPath
Write-Host "Done. Fixtures in $OutDir, manifest in $manifestPath"
Write-Host "Next: protect 3 .xlsm VBA projects manually and add 'expected_protected: true' to their entries."
